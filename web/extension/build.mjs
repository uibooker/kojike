#!/usr/bin/env node
// 从油猴脚本生成扩展 content.js：剥掉 ==UserScript== 头，其余原样。
// 单一事实来源——统计/图表/抓取逻辑只在 jike-circle-stats.user.js 维护，改完跑 `node build.mjs`。
import { readFileSync, writeFileSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(fileURLToPath(import.meta.url));
const srcPath = join(root, '..', 'jike-circle-stats.user.js');
const src = readFileSync(srcPath, 'utf8');
const marker = '// ==/UserScript==';
const idx = src.indexOf(marker);
if (idx < 0) { console.error('UserScript header not found'); process.exit(1); }
const body = src.slice(idx + marker.length).replace(/^\s*\n/, '');

const banner = `// ! Generated by build.mjs from jike-circle-stats.user.js — do not edit; edit the userscript and rebuild.
`;
writeFileSync(join(root, 'content.js'), banner + body);

const ver = src.match(/@version\s+(\S+)/)?.[1] ?? '';
const manifestPath = join(root, 'manifest.json');
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
if (manifest.version !== ver) {
  manifest.version = ver;
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
  console.log(`manifest.json version → ${ver}`);
}
console.log(`content.js: ${statSync(join(root, 'content.js')).size} bytes (v${ver})`);
